// Pre increment

let a = 10;
let b = ++a;  // increase the value first and then assign
console.log(a);
console.log(b);


let a = 10;
let b = --a;  // decerease the value first and then assign
console.log(a);
console.log(b);

let a = 10;
let b = a--;  // decerease the value first and then assign
console.log(a);
console.log(b);

