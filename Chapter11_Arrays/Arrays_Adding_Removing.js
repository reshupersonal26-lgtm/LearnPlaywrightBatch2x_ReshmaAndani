let arr = [1, 2, 3];
console.log(arr);

// Add to End
arr.push(4);
console.log(arr);


//Remove from End
arr.pop();
console.log(arr);

//Push multiple elements in array
arr.push(5, 6);
console.log(arr);

//Add to Beginning
arr.unshift(0);
console.log(arr);

//Remove from Beginning
arr.shift(0);
console.log(arr);

arr.unshift(100);
console.log(arr);
arr.shift();
console.log(arr);